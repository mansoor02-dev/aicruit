"""
Pydantic schemas for request and response models.
"""

from typing import List, Optional
from pydantic import BaseModel, Field


# ── Request Models ───────────────────────────────────────────────────────────

class QuestionEntry(BaseModel):
    """A single interview Q&A pair. Scores and remarks are optional —
    they will be generated by the LLM if not provided."""
    q: str = Field(..., description="The interview question")
    a: str = Field(..., description="The candidate's answer")
    category: str = Field(..., description="Question category")
    ai_score: Optional[int] = Field(
        None, ge=1, le=5,
        description="Pre-existing score (1–5). LLM generates one if omitted.",
    )
    remarks: Optional[str] = Field(
        None,
        description="Pre-existing remarks. LLM generates them if omitted.",
    )


class ReportRequest(BaseModel):
    """POST /generate-report request body."""
    data: List[QuestionEntry] = Field(..., min_length=1)


# ── Internal Model ───────────────────────────────────────────────────────────

class ScoredEntry(BaseModel):
    """An entry after LLM evaluation — always carries a score and remark."""
    q: str
    a: str
    category: str
    score: float = Field(..., ge=0.0, le=10.0, description="Score out of 10")
    remark: str


# ── Response Models ──────────────────────────────────────────────────────────

class CategoryScore(BaseModel):
    """Score for a single category."""
    category: str
    score: float


class RecruiterReport(BaseModel):
    """Report intended for the recruiter."""
    overall_score: float
    category_scores: List[CategoryScore]
    overall_remark: str


class CandidateReport(BaseModel):
    """Feedback intended for the candidate."""
    strengths: List[str]
    improvements: List[str]


class ReportResponse(BaseModel):
    """Full response containing both reports."""
    recruiter_report: RecruiterReport
    candidate_report: CandidateReport
