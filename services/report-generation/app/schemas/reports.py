"""
Pydantic schemas for request and response models.
"""

from typing import List, Optional

from pydantic import BaseModel, Field, field_validator


# ── Request Models ───────────────────────────────────────────────────────────

class QuestionEntry(BaseModel):
    """A single interview Q&A pair. Scores and remarks are optional —
    they will be generated by the LLM if not provided."""
    q: str = Field(..., min_length=1, description="The interview question")
    a: str = Field(..., description="The candidate's answer")
    category: str = Field(..., min_length=1, description="Question category")
    ai_score: Optional[int] = Field(
        None, ge=1, le=5,
        description="Pre-existing score (1–5). LLM generates one if omitted.",
    )
    remarks: Optional[str] = Field(
        None,
        description="Pre-existing remarks. LLM generates them if omitted.",
    )

    @field_validator("q", "category")
    @classmethod
    def strip_required_text(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("must not be blank")
        return value

    @field_validator("a", "remarks")
    @classmethod
    def strip_optional_text(cls, value: Optional[str]) -> Optional[str]:
        return value.strip() if value is not None else None


class ReportRequest(BaseModel):
    """POST /generate-report request body."""
    data: List[QuestionEntry] = Field(..., min_length=1)


# ── Internal Model ───────────────────────────────────────────────────────────

class ScoredEntry(BaseModel):
    """An entry after LLM evaluation — always carries a score and remark."""
    q: str
    a: str
    category: str
    score: float = Field(..., ge=0.0, le=10.0, description="Score out of 10")
    remark: str


class ScoreResult(BaseModel):
    """Structured evaluator result using the input contract's 1–5 scale."""

    score: int = Field(..., ge=1, le=5)
    remark: str = Field(..., min_length=1, max_length=250)

    @field_validator("remark")
    @classmethod
    def strip_remark(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("remark must not be blank")
        return value


class RecruiterSummary(BaseModel):
    """LLM-generated narrative; numeric fields stay deterministic."""

    overall_remark: str = Field(..., min_length=1, max_length=500)

    @field_validator("overall_remark")
    @classmethod
    def strip_overall_remark(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("overall remark must not be blank")
        return value


# ── Response Models ──────────────────────────────────────────────────────────

class CategoryScore(BaseModel):
    """Score for a single category."""
    category: str
    score: float


class RecruiterReport(BaseModel):
    """Report intended for the recruiter."""
    overall_score: float = Field(..., ge=0.0, le=10.0)
    category_scores: List[CategoryScore]
    overall_remark: str = Field(..., min_length=1, max_length=500)


class CandidateReport(BaseModel):
    """Feedback intended for the candidate."""
    strengths: List[str] = Field(..., min_length=1, max_length=3)
    improvements: List[str] = Field(..., min_length=1, max_length=3)

    @field_validator("strengths", "improvements")
    @classmethod
    def validate_feedback_items(cls, values: List[str]) -> List[str]:
        cleaned = [value.strip() for value in values if value.strip()]
        if not cleaned:
            raise ValueError("at least one non-blank feedback item is required")
        return cleaned[:3]


class ReportResponse(BaseModel):
    """Full response containing both reports."""
    recruiter_report: RecruiterReport
    candidate_report: CandidateReport
